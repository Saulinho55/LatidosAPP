export const CURRENCY_SYMBOLS = {
  EUR: '€',
  USD: '$',
  GBP: '£',
};

/**
 * Format latidos as monetary value in the user's currency.
 * 100 latidos = 1 unit of currency.
 */
export const formatLatidosAsMoney = (latidos, currency = 'EUR') => {
  const symbol = CURRENCY_SYMBOLS[currency] || currency;
  const amount = (latidos || 0) / 100;
  
  if (currency === 'EUR') {
    return `${amount.toLocaleString('es-ES', { minimumFractionDigits: 2, maximumFractionDigits: 2 })} ${symbol}`;
  } else if (currency === 'GBP') {
    return `${symbol}${amount.toLocaleString('en-GB', { minimumFractionDigits: 2, maximumFractionDigits: 2 })}`;
  } else {
    // USD
    return `${symbol}${amount.toLocaleString('en-US', { minimumFractionDigits: 2, maximumFractionDigits: 2 })}`;
  }
};
